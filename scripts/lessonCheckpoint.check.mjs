import assert from 'node:assert/strict';
import {lessonCheckpoint,lessonVersion} from '../functions/lessonCheckpoint.mjs';
const task={id:'g3_m1_l4',type:'typing',description:'Печатай',lesson:{explanation:'Первый шаг'}};
const user={role:'student',xp:30,currency:4,equipped:{avatar:'av_1'}};
const state={phase:2,idea:0,path:0,typed:'в',removed:false,choice:null};
const data={taskId:task.id,version:lessonVersion(task),state};
const saved=lessonCheckpoint(user,'saveLessonCheckpoint',data,task);
assert.equal(user.lessonCheckpoints,undefined);assert.equal(saved.user.xp,30);assert.equal(saved.user.currency,4);
assert.deepEqual(lessonCheckpoint(saved.user,'getLessonCheckpoint',data,task).checkpoint.state,state);
assert.equal(lessonCheckpoint(saved.user,'getLessonCheckpoint',data,{...task,description:'Новая версия'}).checkpoint,null);
assert.throws(()=>lessonCheckpoint(saved.user,'saveLessonCheckpoint',{...data,version:'old'},task));
assert.throws(()=>lessonCheckpoint(user,'saveLessonCheckpoint',{...data,state:{...state,phase:99}},task));
assert.throws(()=>lessonCheckpoint({...user,role:'teacher'},'saveLessonCheckpoint',data,task));
assert.throws(()=>lessonCheckpoint(user,'saveLessonCheckpoint',data,{...task,id:'g8_l1'}));
assert.equal(saved.checkpoint.mode,'learn');
console.log('lessonCheckpoint: restore, version invalidation, validation, role, pilot limits and no rewards OK');
const {practiceDraft}=await import('../functions/lessonCheckpoint.mjs');
const practice={active:true,typed:'в',option:null};
const draft=practiceDraft(user,'savePracticeDraft',{version:lessonVersion(task),state:practice},task);
assert.deepEqual(practiceDraft(draft.user,'getPracticeDraft',{},task).draft.state,practice);
assert.equal(draft.user.xp,user.xp);
assert.equal(draft.user.completedTaskIds,undefined);
assert.equal(practiceDraft(draft.user,'getPracticeDraft',{}, {...task,typingConfig:{targetText:'Новый'}}).draft,null);
assert.throws(()=>practiceDraft(user,'savePracticeDraft',{version:lessonVersion(task),state:{...practice,option:100}},task));
console.log('practiceDraft: input restore, criterion version invalidation, bounds and no completion/rewards OK');
