 const logged = await call('login',{role:'teacher',name:' Учитель ',password:'old'});
 assert.equal(logged.token,'test:t_1');
 assert.ok(!snapshot().users.legacyTeacher.password);
 assert.ok(snapshot().credentials[credentialKey('teacher','Учитель')].hash);
