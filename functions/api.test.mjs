 assert.equal(newAccount.token,newAccountRetry.token);
 await assert.rejects(call('login',{role:'teacher',name:'Новый',password:'bad-password'}),{code:'unauthenticated'});
 const {default:catalog} = await import('./catalog.json',{with:{type:'json'}});
 const taskId = catalog.tasks[0].id;
